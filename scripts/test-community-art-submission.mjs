import assert from 'node:assert/strict'
import fs from 'node:fs'

const migration = fs.readFileSync('supabase/migrations/20260718083007_community_art_text_correction.sql', 'utf8')
const api = fs.readFileSync('api/art-studio.ts', 'utf8')
const page = fs.readFileSync('src/pages/ArtStudioPage.tsx', 'utf8')
const service = fs.readFileSync('src/services/communityArtService.ts', 'utf8')
const validation = fs.readFileSync('shared/domains/art-studio/textValidation.ts', 'utf8')

const artwork = '  ┌─🐱─┐\n  │ o.o │\n\n  └─^─┘  '
assert.equal(Array.from(artwork).length, 28)
assert.equal(artwork.split('\n').length, 4)
assert.equal(artwork, '  ┌─🐱─┐\n  │ o.o │\n\n  └─^─┘  ')
assert.match(validation, /Array\.from\(artwork\)/)
assert.match(validation, /artwork\.split\('\\n'\)/)
assert.match(validation, /input\.attributionType === 'custom'/)
assert.doesNotMatch(validation, /input\.attributionType !== 'anonymous' && !input\.attributionName/)
assert.match(migration, /artwork_text text/)
assert.match(migration, /generated always as \(char_length\(artwork_text\)\)/)
assert.match(migration, /generated always as \([\s\S]*?length\(artwork_text\)/)
assert.match(migration, /status = 'pending'/)
assert.match(migration, /compatibility_status.*needs_testing/s)
assert.match(migration, /where status = 'published'/)
assert.doesNotMatch(migration, /grant select \(.*moderation_note_private/s)
assert.match(api, /artworkText/)
assert.match(api, /status: 'pending'/)
assert.match(api, /Only approved submissions can be published/)
assert.match(api, /moderation_note_private/)
assert.doesNotMatch(api, /storage\.from|image_width|file_size/)
assert.match(page, /<pre>/)
assert.match(page, /copyText\(text: string\)/)
assert.match(page, /copyApprovedPayload\(text\)/)
assert.match(page, /approvedCopyPayload/)
assert.match(api, /raw_source_text/)
