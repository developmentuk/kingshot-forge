assert.match(page, /onSubmit=\{submit\}/)
assert.match(page, /if \(saving\) return/)
assert.match(page, /validationIssues\.map\(\(issue\) => issue\.message\)/)
assert.match(page, /disabled=\{saving\}/)
assert.match(page, /role="alert"/)
assert.match(page, /Artwork submitted for review\. Current status: Pending\./)
assert.match(page, /draft is still here/)
assert.doesNotMatch(page, /onClick=\{submit\}/)
assert.match(page, /type="file"/)
assert.match(page, /Upload text file \(exact bytes\)/)
assert.match(page, /Text entered in the browser/)
assert.match(service, /response\.ok/)
assert.match(service, /response\.json\(\)/)
assert.match(service, /draft is still here/)
assert.doesNotMatch(service, /SUPABASE_SERVICE_ROLE|SUPABASE_SECRET_KEY|storage_path/)
console.log('Community Art Studio text preservation and publication boundary tests passed.')
