import assert from 'node:assert/strict'
import fs from 'node:fs'
import { analyseText, repairText } from '../shared/domains/art-studio/rendering.ts'
import { auditTransition, classifyCharacter, fingerprint, graphemes, restoreOriginal } from '../shared/domains/art-studio/preservation.ts'

const fixture = fs.readFileSync('fixtures/community-art/wow-im-so-cute/wow-im-so-cute.txt', 'utf8')
const inventory = JSON.parse(fs.readFileSync('fixtures/community-art/wow-im-so-cute/expected-inventory.json', 'utf8'))
assert.equal(inventory.code_point_count, 276)
assert.equal(inventory.grapheme_count, 258)
assert.equal(inventory.entries.length, 276)
assert.equal(inventory.entries.filter((entry) => entry.glyph === '　').length, 27)
assert.equal(inventory.entries.filter((entry) => /\p{Extended_Pictographic}/u.test(entry.glyph)).length, 2)
assert.equal(inventory.entries.filter((entry) => /[\u1100-\u115F\u2329\u232A\u2E80-\u303E\u3040-\uA4CF\uAC00-\uD7A3\uF900-\uFAFF\uFE10-\uFE19\uFE30-\uFE6F\uFF00-\uFF60\uFFE0-\uFFE6]/u.test(entry.glyph)).length, 40)
assert.equal(graphemes(fixture).length, 258)
assert.equal(analyseText(fixture).source, fixture)
assert.equal(repairText(fixture).text, fixture)
assert.equal(repairText(fixture).operations.length, 0)
assert.equal(classifyCharacter('未知'), 'unverified')
assert.equal(classifyCharacter('！', true), 'verified_in_specific_context')
assert.equal(classifyCharacter('　', true), 'verified_in_specific_context')
assert.equal(classifyCharacter('😀', true), 'verified_in_specific_context')
assert.equal(classifyCharacter('\u0000'), 'unsafe_control')
const changed = auditTransition('moderator-edit', 'A　B！', 'A B! ', 'moderator', true)
assert.equal(changed.userApproved, true)
assert.equal(changed.replacements.length > 0, true)
assert.equal(changed.whitespaceChanges.length > 0, true)
const restored = restoreOriginal(fixture)
assert.equal(restored.text, fixture)
assert.equal(restored.hash, fingerprint(fixture))
assert.equal(restored.equal, true)
const migration = fs.readFileSync('supabase/migrations/20260722110000_art002l_character_preservation.sql', 'utf8')
const api = fs.readFileSync('api/art-studio.ts', 'utf8')
assert.match(migration, /approved payload changes require a moderator-confirmed audit operation/)
assert.match(migration, /raw_source_text is immutable/)
assert.match(api, /payload = approvedPayload \?\? .*raw_source_text/)
assert.match(api, /Confirm every payload change with a moderator-approved audit operation/)
console.log('ART-002L preservation tests passed: inventory, classification, non-mutating repair, restore and approval guard.')
